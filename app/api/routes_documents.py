"""Document metadata, under /orgs/{org_id}/documents.

File bytes and object storage are a later phase. This step manages the
metadata row only. Phase 1 RLS decides everything:
  read    document.read AND (owner OR visibility 'organization'
          OR (visibility 'project' AND (participant OR project.read_all)))
  create  document.upload AND owner = me AND (no project OR I participate)
  update  document.update AND owner = me (title, visibility, project_id)
  delete  document.delete AND owner = me
Admins get no exception: an org admin can't read or delete someone's private
document.

storage_key is generated by the database ('org/<org id>/<random uuid>') and
never accepted from, or shown to, the client: a client-chosen key is a path
traversal / object-overwrite risk once real storage exists. size_bytes and
sha256 are the client's declaration; the storage phase must verify them
against the uploaded bytes before the document is served.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Annotated, Any, Literal

from fastapi import APIRouter, Query, Response, status
from psycopg import sql
from psycopg.rows import dict_row
from pydantic import BaseModel, Field

from app.api.deps import OrgConn
from app.api.models import StrictModel, patch_values, text
from app.api.pagination import Page, Paging, paginate
from app.api.routes_projects import require_visible_project
from app.api.rows import fetch_one, write_or_404

router = APIRouter(prefix="/orgs/{org_id}/documents", tags=["documents"])

Visibility = Literal["private", "project", "organization"]
ContentType = Literal[
    "application/pdf", "text/plain", "text/markdown",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
]
Title = text(300)
MAX_SIZE = 50 * 1024 * 1024   # same limit as the column CHECK

DOC_COLS = ("id, owner_id, project_id, title, content_type, size_bytes, "
            "encode(sha256, 'hex') AS sha256, visibility, created_at, updated_at")


class DocumentOut(BaseModel):
    id: uuid.UUID
    owner_id: uuid.UUID
    project_id: uuid.UUID | None
    title: str
    content_type: ContentType
    size_bytes: int
    sha256: str
    visibility: Visibility
    created_at: datetime
    updated_at: datetime


class DocumentCreate(StrictModel):
    title: Title
    content_type: ContentType
    size_bytes: Annotated[int, Field(ge=0, le=MAX_SIZE)]
    sha256: Annotated[str, Field(pattern=r"^[0-9a-f]{64}$")]
    project_id: uuid.UUID | None = None
    visibility: Visibility = "private"      # secure default, same as the column


class DocumentUpdate(StrictModel):
    title: Title = None                      # explicit null -> 422
    visibility: Visibility = None
    project_id: uuid.UUID | None = None      # null detaches from the project


def _doc(row: dict[str, Any]) -> DocumentOut:
    return DocumentOut(**row)


@router.get("", response_model=Page[DocumentOut])
def list_documents(conn: OrgConn, page: Paging,
                   project_id: uuid.UUID | None = None,
                   visibility: Visibility | None = None,
                   mine: Annotated[bool, Query()] = False):
    # These are filters for the caller's convenience, not access control:
    # without them the result is still exactly the RLS-visible set.
    where, params = [], []
    if project_id is not None:
        where.append("project_id = %s")
        params.append(project_id)
    if visibility is not None:
        where.append("visibility = %s")
        params.append(visibility)
    if mine:
        where.append("owner_id = secureai_rls.current_user_id()")
    return paginate(conn, f"SELECT {DOC_COLS} FROM secureai.documents", where, params, page, _doc)


@router.post("", response_model=DocumentOut, status_code=status.HTTP_201_CREATED)
def create_document(conn: OrgConn, body: DocumentCreate) -> DocumentOut:
    if body.project_id is not None:
        # Hidden or nonexistent project -> 404 before any write, so a WITH CHECK
        # 403 can't confirm that a hidden project exists.
        require_visible_project(conn, body.project_id)
    row = conn.cursor(row_factory=dict_row).execute(
        "INSERT INTO secureai.documents (organization_id, owner_id, project_id, title, storage_key, "
        "content_type, size_bytes, sha256, visibility) VALUES "
        "(secureai_rls.current_org_id(), secureai_rls.current_user_id(), %s, %s, "
        " 'org/' || secureai_rls.current_org_id() || '/' || gen_random_uuid(), "
        " %s, %s, decode(%s, 'hex'), %s) "
        f"RETURNING {DOC_COLS}",
        (body.project_id, body.title, body.content_type, body.size_bytes, body.sha256,
         body.visibility)).fetchone()
    return _doc(row)


@router.get("/{document_id}", response_model=DocumentOut)
def get_document(conn: OrgConn, document_id: uuid.UUID) -> DocumentOut:
    return _doc(fetch_one(conn, f"SELECT {DOC_COLS} FROM secureai.documents WHERE id = %s",
                          (document_id,), "Document"))


@router.patch("/{document_id}", response_model=DocumentOut)
def update_document(conn: OrgConn, document_id: uuid.UUID, body: DocumentUpdate) -> DocumentOut:
    values = patch_values(body)
    if values.get("project_id") is not None:
        require_visible_project(conn, values["project_id"])
    query = sql.SQL("UPDATE secureai.documents SET {} WHERE id = %s RETURNING {}").format(
        sql.SQL(", ").join(sql.SQL("{} = %s").format(sql.Identifier(k)) for k in values),
        sql.SQL(DOC_COLS))
    return _doc(write_or_404(conn, query, [*values.values(), document_id],
                             table="documents", row_id=document_id, what="Document"))


@router.delete("/{document_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_document(conn: OrgConn, document_id: uuid.UUID) -> Response:
    write_or_404(conn, "DELETE FROM secureai.documents WHERE id = %s RETURNING id",
                 (document_id,), table="documents", row_id=document_id, what="Document")
    return Response(status_code=status.HTTP_204_NO_CONTENT)
